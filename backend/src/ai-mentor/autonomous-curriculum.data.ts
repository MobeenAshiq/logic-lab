/**
 * Returns curriculum metadata for a day index.
 * If day > 45, generates systematic progression topics (advanced distributed systems, microservices, AI inference).
 */
export function getBlueprintForDay(dayIndex: number): CurriculumDayBlueprint {
  const existing = CURRICULUM_BLUEPRINTS.find((b) => b.dayIndex === dayIndex);
  if (existing) return existing;

  const weekNumber = Math.ceil(dayIndex / 7);
  return {
    dayIndex,
    weekNumber,
    phase: 'advanced_systems',
    moduleName: `Advanced Systems & Engineering (Week ${weekNumber})`,
    topic: `System Engineering Topic Day ${dayIndex}: Scalable Architecture & Deep Computer Science`,
    analogyHook: 'A high-throughput airport logistics network routing flights, baggage, and passengers with zero single points of failure.',
    targetStack: 'fullstack',
  };
}

